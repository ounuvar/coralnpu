"""Packages the CoralNPU CL as an AWS HDK custom-logic directory (a tarball).

Input: the Vivado project tcl that FuseSoC wrote for cl_coralnpu_core (from the
//fpga:build_cl_coralnpu_elab_only_* targets), whose sources sit in src/ next to it, plus the
files under fpga/f2. Output: cl_coralnpu/ with the HDK layout, ready to unpack into
$HDK_DIR/cl/developer_designs/:

  design/cl_coralnpu.sv, design/cl_id_defines.vh   CL top (read by the HDK flow)
  design/coralnpu_src/...                          SoC sources, as FuseSoC staged them
  build/scripts/synth_cl_coralnpu.tcl              HDK synthesis script
  build/scripts/cl_coralnpu_sources.tcl            ordered sources, include dirs, defines,
                                                   parameters (generated here)
  build/constraints/*.xdc                          user constraints
  verif/tests/*.sv, verif/scripts/*                HDK simulation (top.*.f generated here)
"""

import argparse
import io
import os
import re
import tarfile

SRC_SUBDIR = "design/coralnpu_src"


def parse_project(tcl_path):
    """Returns (sources, include_dirs, defines, generics) from a FuseSoC Vivado project tcl."""
    sources, include_dirs, defines, generics = [], [], [], []
    with open(tcl_path) as f:
        for line in f:
            line = line.strip()
            m = re.match(r"read_verilog(?: -sv)? \{(.+)\}$", line)
            if m:
                sources.append(m.group(1))
                continue
            m = re.match(r"set_property include_dirs \[list (.*)\] ", line)
            if m:
                include_dirs = m.group(1).split()
                continue
            m = re.match(r"set_property verilog_define \{(.*)\} ", line)
            if m:
                defines = m.group(1).split()
                continue
            m = re.match(r"set_property generic \{(.*)\} ", line)
            if m:
                # An empty string parameter (MemInitFile=) is left at its default.
                generics = [
                    g for g in m.group(1).split() if not g.endswith("=")
                ]
    if not sources:
        raise SystemExit(f"no sources found in {tcl_path}")
    return sources, include_dirs, defines, generics


def tcl_list(items):
    return " \\\n  ".join(items)


def sources_tcl(sources, include_dirs, defines, generics):
    src = "$::env(CL_DIR)/" + SRC_SUBDIR
    lines = [
        "# Generated by fpga/f2/build/scripts/export_cl_coralnpu.py from the FuseSoC project of",
        "# cl_coralnpu_core. Do not edit; re-export instead.",
        f"set coralnpu_src {src}",
        "set coralnpu_sources [list \\\n  " +
        tcl_list(f"$coralnpu_src/{s}" for s in sources) + " \\\n]",
        "set coralnpu_include_dirs [list \\\n  " +
        tcl_list(f"$coralnpu_src/{d}" for d in include_dirs) + " \\\n]",
        "set coralnpu_defines [list " + " ".join(defines) + "]",
        "set coralnpu_generics [list " + " ".join(generics) + "]",
    ]
    return "\n".join(lines) + "\n"


def sim_filelist(sources, include_dirs, defines):
    """File list for the HDK simulation (top.<simulator>.f)."""
    src = "$CL_DIR/" + SRC_SUBDIR
    lines = [
        "# Generated by fpga/f2/build/scripts/export_cl_coralnpu.py. Do not edit.",
        "-define CL_NAME=cl_coralnpu",
        "-define DISABLE_VJTAG_DEBUG",
    ]
    lines += [f"-define {d}" for d in defines]
    lines += [f"-include {src}/{d}" for d in include_dirs]
    lines += ["-include $CL_DIR/design/", "-include $CL_DIR/verif/tests"]
    lines += [f"{src}/{s}" for s in sources]
    lines += [
        "$CL_DIR/design/cl_coralnpu.sv",
        "-f $HDK_COMMON_DIR/verif/tb/filelists/tb.${SIMULATOR}.f",
        "${TEST_NAME}",
    ]
    return "\n".join(lines) + "\n"


def add_bytes(tar, name, data, mode=0o644):
    info = tarfile.TarInfo(name)
    info.size = len(data)
    info.mode = mode
    tar.addfile(info, io.BytesIO(data))


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--project_tcl", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--design", nargs="*", default=[])
    parser.add_argument("--scripts", nargs="*", default=[])
    parser.add_argument("--timing_xdc", required=True)
    parser.add_argument("--tests", nargs="*", default=[])
    parser.add_argument("--verif_scripts", nargs="*", default=[])
    args = parser.parse_args()

    base = os.path.dirname(args.project_tcl)
    sources, include_dirs, defines, generics = parse_project(args.project_tcl)
    top = "cl_coralnpu"

    # Bazel and FuseSoC stage sources as symlinks into the local cache; store the
    # files themselves so the package unpacks on another machine.
    with tarfile.open(args.out, "w:gz", dereference=True) as tar:
        # SoC sources and the include directories, as staged by FuseSoC.
        staged = set(sources)
        for d in include_dirs:
            full = os.path.join(base, d)
            if d == "." or not os.path.isdir(full):
                continue
            for name in sorted(os.listdir(full)):
                if os.path.isfile(os.path.join(full, name)):
                    staged.add(os.path.join(d, name))
        for rel in sorted(staged):
            tar.add(
                os.path.join(base, rel), arcname=f"{top}/{SRC_SUBDIR}/{rel}"
            )
        for path in args.design:
            tar.add(path, arcname=f"{top}/design/{os.path.basename(path)}")
        for path in args.scripts:
            tar.add(
                path, arcname=f"{top}/build/scripts/{os.path.basename(path)}"
            )
        add_bytes(
            tar, f"{top}/build/scripts/cl_coralnpu_sources.tcl",
            sources_tcl(sources, include_dirs, defines, generics).encode()
        )
        # User constraints: the CL timing goes in cl_timing_user.xdc; the rest are empty.
        tar.add(
            args.timing_xdc,
            arcname=f"{top}/build/constraints/cl_timing_user.xdc"
        )
        for name in ("cl_synth_user.xdc", "small_shell_cl_pnr_user.xdc",
                     "xdma_shell_cl_pnr_user.xdc"):
            add_bytes(
                tar, f"{top}/build/constraints/{name}",
                b"# No user constraints (see cl_timing_user.xdc).\n"
            )
        for path in args.tests:
            tar.add(
                path, arcname=f"{top}/verif/tests/{os.path.basename(path)}"
            )
        for path in args.verif_scripts:
            tar.add(
                path, arcname=f"{top}/verif/scripts/{os.path.basename(path)}"
            )
        filelist = sim_filelist(sources, include_dirs, defines).encode()
        for sim in ("xsim", "vcs", "questa"):
            add_bytes(tar, f"{top}/verif/scripts/top.{sim}.f", filelist)

    print(
        f"wrote {args.out}: {len(sources)} SoC sources, defines {' '.join(defines)}, "
        f"parameters {' '.join(generics)}"
    )


if __name__ == "__main__":
    main()
